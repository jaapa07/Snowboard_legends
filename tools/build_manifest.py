def validate(e):
    p = os.path.join(ROOT, e["file"])
    problems = []
    if not os.path.isfile(p):
        return "missing", ["file not found"]
    size = os.path.getsize(p)
    e["bytes"] = size
    e["sha1"] = sha(p)
    if size == 0:
        problems.append("empty file")
    if e["license"] not in KNOWN_LICENSES:
        problems.append("unknown license")
    imported = e["file"].endswith((".png", ".glb", ".ogg", ".wav", ".otf"))
    if imported and not os.path.isfile(p + ".import"):
        problems.append("no Godot import metadata (.import)")
    try:
        if e["file"].endswith(".glb"):
            j = glb_json(p)
            e["meshes"] = len(j.get("meshes", []))
            e["materials"] = len(j.get("materials", []))
            if e["meshes"] == 0:
                problems.append("GLB has no meshes")
            if e["type"] == "rider_model":
                clips = [a.get("name", "") for a in j.get("animations", [])]
                e["clips"] = len(clips)
                miss = [c for c in REQUIRED_CLIPS if c not in clips]
                if miss:
                    problems.append("missing clips " + ",".join(miss))
                if not j.get("skins"):
                    problems.append("no skin/rig")
        elif e["file"].endswith(".png"):
            w, h = png_size(p)
            e["size_px"] = [w, h]
            if w < 16 or h < 16 or w > 4096 or h > 4096:
                problems.append("texture size out of range")
            if e["type"] in ("portrait", "item_icon") and not (128 <= w <= 512):
                problems.append("icon/portrait must be 128-512 px")
            if e["type"] == "texture" and (w & (w - 1) or h & (h - 1)):
                problems.append("material texture not power of two")
        elif e["file"].endswith(".json"):
            json.load(open(p))
    except Exception as ex:  # noqa
        problems.append("parse error: %s" % ex)
    if problems:
        return "in_progress", problems
    return ("verified" if e["type"] in VERIFIED_BY else "integrated"), []


def main():
    check_only = "--check" in sys.argv
    entries = collect()
    bad = []
    for e in entries:
        st, probs = validate(e)
        e["status"] = st
        if probs:
            e["problems"] = probs
        if st in VERIFIED_BY.get(e["type"], "") or st == "verified":
            e["verified_by"] = VERIFIED_BY.get(e["type"])
        if e["required"] and st in ("missing", "in_progress"):
            bad.append(e)
    if not check_only:
        man = {"schema": 1, "generated_by": "tools/build_manifest.py", "count": len(entries), "assets": entries}
        with open(os.path.join(ROOT, "assets.manifest.json"), "w") as f:
            json.dump(man, f, indent=1, ensure_ascii=False)
        write_status(entries)
    by = {}
    for e in entries:
        by[e["status"]] = by.get(e["status"], 0) + 1
    print("manifest: %d assets %s" % (len(entries), by))
    for e in bad:
        print("  BLOCKING %s (%s): %s" % (e["id"], e["status"], "; ".join(e.get("problems", []))))
    sys.exit(1 if bad else 0)


def write_status(entries):
    groups = {}
    for e in entries:
        groups.setdefault(e["type"], []).append(e)
    L = ["# ASSET_STATUS — Snowboard Legends 3D", "",
         "Gerado por `python3 tools/build_manifest.py` a partir dos arquivos presentes (não editar à mão).",
         "Estados: `missing` (arquivo ausente), `in_progress` (presente mas reprovado na validação), `integrated` (presente, validado e referenciado pelo jogo),",
         "`verified` (além disso carregado por teste automatizado e/ou visível em captura real). O build de release roda `--check` e falha com `missing`/`in_progress`.", "",
         "| Tipo | Qtd | missing | in_progress | integrated | verified | Verificação |", "|---|---:|---:|---:|---:|---:|---|"]
    for t, es in groups.items():
        c = {s: sum(1 for e in es if e["status"] == s) for s in ("missing", "in_progress", "integrated", "verified")}
        L.append("| %s | %d | %d | %d | %d | %d | %s |" % (t, len(es), c["missing"], c["in_progress"], c["integrated"], c["verified"], VERIFIED_BY.get(t, "validação de arquivo/formato")))
    L += ["", "## Detalhe", "", "| id | arquivo | estado | método de produção | licença | observações |", "|---|---|---|---|---|---|"]
    for e in entries:
        obs = []
        if "clips" in e:
            obs.append("%d clips" % e["clips"])
        if "size_px" in e:
            obs.append("%dx%d" % tuple(e["size_px"]))
        if "meshes" in e:
            obs.append("%d meshes" % e["meshes"])
        obs += e.get("problems", [])
        L.append("| %s | `%s` | %s | %s | %s | %s |" % (e["id"], e["file"], e["status"], e["method"], e["license"], ", ".join(obs)))
    with open(os.path.join(ROOT, "ASSET_STATUS.md"), "w") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
