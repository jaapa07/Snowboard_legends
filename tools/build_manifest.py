def glb_json(path):
    with open(path, "rb") as f:
        head = f.read(12)
        magic, ver, length = struct.unpack("<4sII", head)
        if magic != b"glTF":
            raise ValueError("not a GLB")
        clen, ctype = struct.unpack("<II", f.read(8))
        return json.loads(f.read(clen))


def png_size(path):
    with open(path, "rb") as f:
        d = f.read(24)
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    return struct.unpack(">II", d[16:24])


def sha(path):
    h = hashlib.sha1()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()[:12]


def entry(aid, rel, typ, method, source=None, deps=None, license_="project-original", required=True, extra=None):
    return {"id": aid, "path": "res://" + rel, "file": rel, "type": typ, "license": license_, "method": method,
            "source": source, "dependencies": deps or [], "required": required, "fallback": None, **(extra or {})}


