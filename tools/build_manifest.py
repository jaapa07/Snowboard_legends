"""Builds and validates assets.manifest.json and ASSET_STATUS.md from the files actually present.

Usage:
    python3 tools/build_manifest.py            # write manifest + status, exit 1 if a required asset fails validation
    python3 tools/build_manifest.py --check    # validate only (used before exporting a release build)

Validation (spec §13/§19): file exists and is not empty, Godot import metadata present, GLB parses and has meshes,
rider GLBs contain every required animation clip, textures/sprites have sane power-of-two-ish sizes,
every entry has a known license, and no required asset is `missing` or `in_progress`.
Licenses are recorded as they are known: content generated by this repository's own scripts is
`project-original` (owned by the repository owner); third-party files carry their real license.
"""
